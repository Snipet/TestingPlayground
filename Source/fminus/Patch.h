// Source/fminus/Patch.h: one program, compiled for the plugin and ready to play (JUCE-free). A program is FMinus source
// whose main module the plugin runs, in the first of its files (Sources.h); the others are what its #includes read,
// by name. What the plugin asks of the main module depends on the plugin's kind (products/<key>.cmake):
//
//   an effect: module Effect
//       param ...;                                              the dials (Controls.h), at most kMaxControls
//       void init(float rate);                                  optional: when the program starts, and again when the
//                                                               sample rate changes, off the audio thread
//       void process(float* restrict left, float* restrict right, int n);
//                                                               n samples of both channels, in place, on the audio
//                                                               thread (a mono bus: `right` a copy of the left, unheard)
//       void end();                                             optional: before the program goes, off the audio thread
//
//   an instrument: module Voice, one instance a voice (kVoices of them, the Engine assigning notes)
//       param ...;                                              the dials, the same values in every voice
//       void init(float rate);                                  optional, as an effect's
//       void start(float note, float velocity);                 a note-on: the MIDI note number (69 is A 440 Hz) and
//                                                               0..1; the voice may have played another note before
//       void stop();                                            optional: the note-off (the key, or All Notes Off)
//       void legato(float note, float velocity);                optional, a mono program's (below, "Mono"): the
//                                                               sounding voice's new note, in place of a start
//       bool process(float* restrict left, float* restrict right, int n);
//                                                               the voice's next n samples into the buffers, which
//                                                               arrive at 0 (write or add); false once it is silent
//                                                               for good, which frees the voice
//       void end();                                             optional
//
//   either kind, optionally: module Shared, made once for the program, which every field of the main module of type
//   Shared* points at: what an instrument's voices share (wavetables, lookup tables, a sample), built once
//       void init(float rate);                                  optional: before the main module's instances' init,
//                                                               off the audio thread (again when the rate changes)
//       void end();                                             optional: after theirs
//     and an instrument's, optionally (below, "Shared on its own"), on the audio thread:
//       void tick(int n);                                       every 16 samples (n = 16), whether or not a voice sounds
//       void noteOn(float note, float velocity);                a note-on, before its voice's start
//       void noteOff(float note);                               that note's end, before its voice's stop
//       param ...;                                              one named as a dial reads that dial (read-only)
//   The audio thread reads it through those pointers; it is the plugin's to free, never a voice's.
//
//   either kind, optionally: module Host, from host.fm, the plugin's own file (#include "host.fm"; hostSource()): one
//   instance, which every field of type Host* of the main module (and of Shared) points at, and which the Engine fills
//   before every call of start, stop and process (setHost): the tempo, the song's position at the call's first sample,
//   the time signature, whether the host plays, and an instrument's mod wheel, pitch bend, aftertouch and sustain
//   pedal, and a racing wheel's steering, pedals, gear and buttons. A program reads it, never writes it.
//
// Circuits. A file of the program whose name ends in .cir is a SPICE-style netlist (fminus/Circuits.h): an #include of
// it reads the FMinus module FMinus's circuit compiler generates from it (fminus::circuit::generate), generated when an
// #include first reaches it (once a compile: compile()'s second pass reads it again), with the self-test's answer for
// it when the store holds one (circuits::answers()). A netlist no #include reaches is never generated by compile(), so
// a broken tab the program does not include never stops RUN; check() generates it too, for its messages. The netlist's
// errors ("pedal.cir:7:1: error: ...") stop the compile, ahead of FMinus's own messages; FMinus's messages on a
// generated module are cited at the netlist's lines (circuits::Generator::recite); its warnings, and the provisional
// note of a netlist whose configuration waits for the self-test, are notes. The program itself (the first file) is
// FMinus, never a netlist. Result::circuitJobs are the self-tests the compile wants (a netlist with an open
// configuration and no answer: its provisional configuration plays meanwhile; the Compiler hands those of a compile
// that plays to its SelfTester, and compiles the program again once an answer lands: Compiler.h, "The self-test"),
// Result::circuitKeys the keys of every netlist generated with a configuration to choose; the recipe keeps the
// generated texts (Recipe::circuits), so freeze(), ir() and frozenIr() read the modules the program was compiled with
// and never generate again: a frozen copy keeps its program's layout whatever the store holds by then. It keeps the
// configuration each was generated with too (Recipe::pins, Sources.h's CircuitPins), which compile() takes back: a
// recording's replay compiles the program that played with its pins, so it plays what played, not the store's answer.
//
// A circuit's pots become dials. A field of the main module (a scalar or an array) whose type is a netlist's module
// gets that netlist's pots as dials and its switches as int dials (lang::circuitDials, Lang.h: what the GUI sandbox
// reads too), after the program's own params, in field order, each field's pots in .pot order and then its switches,
// within the kMaxControls slots (past them, a note; the argument stays at its default): a pot real 0 to 1 shown 0-100 %
// at its .pot default, linear (its taper is set()'s), a switch an int over its positions at its default; named as the
// pot is, or <field>_<pot> when another dial has that name. An array's elements share one set of dials. Unless the
// program calls that module's set() itself: a member call named set in its FMinus files whose receiver is of that
// module, or whose receiver Lang cannot type (the test is conservative, so a pot is never driven twice), leaves those
// fields to the program, with no dials (the binding's `why` says so: never a compile message, since a program that
// drives its own pots, as the examples do, is right). Each binding is checked against what FMinus compiled (the
// field's type and extent, the generated set()'s arguments, the params' names): one that differs gets no dials and a
// note. For each bound field compile() appends a shim, all of one type, `void playground_circuit_<k>(Effect* self,
// float* restrict v) [[clang::nonblocking]]`, calling every element's set() with v (a switch's position cast to int);
// the Engine calls them through setCircuits() on the absolute 16-sample grid, only while a bound dial moves or a
// switch ramps, and once before an instance's first call (Engine.h, "Circuit dials"). These dials are no FMinus
// parameters: a frozen copy folds none of them, and plays the instances' set() state as the program's code does; a pot
// that moves drops it, as any dial does. The recipe keeps the bindings and the shims' count (Recipe::bindings), so
// freeze(), ir() and frozenIr() find the shims the source carries.
//
// Probes. Every netlist is generated with FMinus's probes on (Circuits.h, "Probes"), so a netlist's module carries the
// probe fields (circuits::kProbeFields) after its own, in the program, its frozen copy and every recompile alike. For
// each field of the main module (a scalar or an array) whose type is a netlist's module, compile() keeps a probe table
// entry (probed(): the field, its netlist, its elements' paths and the netlist's nodes, which CompileStatus::probes
// shows): each element's offset in an instance and the probe fields' offsets in it, from FMinus's
// Program::Module::Field, each checked against its type, the module's size and the instance's (a field that differs
// gets no entry). The accessors below are the Engine's, on the audio thread between calls (noexcept, nothing
// allocated, every index checked): arm a slot set into one element of one instance, disarm it, read how many samples
// it wrote, its rings, and its stats (read and zeroed). Nothing else writes the probe fields; the field map
// (fieldMap(), unmapped()) leaves them out.
//
// Conditionals and warnings. Every compile here, each pass of compile(), check(), freeze(), ir() and frozenIr(), defines
// the plugin's macros (lang::kDefines: DEBUG) as FMinus's Program::Options::defines, so a program's #ifdef DEBUG groups
// are read wherever the plugin builds it, the frozen copy too: it plays through the program's instances, so a field an
// #ifdef DEBUG declares must be in both, and it must sound and feed the displays as the program does. A group a
// conditional skips is no part of the program for the plugin either: the panel's #pragma lines are read from the
// files as FMinus read them (lang::conditionals). FMinus's warnings (Program::warnings: -Wswitch, a switch on an
// enumerated value that misses some of its constants without a default) are about a program that compiles and plays
// as written: compile() gives pass 1's in Result::notes (a netlist's module's cited at the netlist, as its errors),
// check() among its messages, each a "file:line:col: warning: ... [-Wswitch]" line (clang's note after it at its own
// place left out: it would mark the word again); a program that fails has them among its errors, where FMinus puts
// them.
//
// The methods the audio thread calls (process, start, stop) must not allocate: FMinus refuses a program whose methods
// could reach calloc, malloc or free from them (init and end may: a delay line's memory). They need no
// [[clang::nonblocking]] of their own: the plugin calls each through a function of its own with the type it calls it
// by, appended to the program and marked nonblocking (compile() below), so FMinus checks the method's types and its
// effects, and a method of another type is an error, not a crash.
//
// Controls. The main module's first kMaxControls parameters, in declaration order, are the plugin's dials (the first
// 32 the host's parameters, the next 32 the panel's own: Controls.h; the Patch treats both alike): a float is bound
// as a stream (Program::Binding::stream; the Engine smooths it and passes a buffer while it moves, null while it holds
// still), an int and a bool as knobs. Parameters past kMaxControls, and those of the modules the main module holds,
// keep their fminus::default (they are set, in every instance, before init runs).
//
// The panel. A .gui file (GuiSpec.h), the first one, gives the interface, the tapers, units and scales of the dials, and
// the taps: where each field a display reads sits (in an instance, or in Shared; an array's element where the display
// names one). What reading it needs of the compile is kept (Recipe::panel, PanelBase: the fields a display may name and
// where each sits, so that any source displaySource reads resolves, the files FMinus read,
// whether they hold #pragma panel lines), so readPanel() reads a .gui file again with no compile: the Compiler applies
// an edit of the panel's files alone so to the program that plays (Compiler.h, "A panel's edit"), and its new taps go
// to the Engine (Engine::setTaps, read through tapOf()) rather than into this Patch, which the audio thread reads.
//
// Shared on its own (an instrument's). Shared's init runs when the program compiles, before any dial is known, so it sees
// each dial at its default; and without these hooks Shared moves only when a voice's call moves it. So an instrument's
// Shared may also have the methods below, each optional, which the Engine calls (Engine.h, "Shared on its own") through
// a nonblocking shim each, appended as the main module's are, and only when the method is declared as here
// (lang::sharedHooks: a method of the name declared otherwise is never called, with a note at its place, so a program
// that has one for its own use plays as it did):
//   tick(int n)       at every absolute multiple of 16 samples (Engine::kGrid; n is 16), after the events at that sample
//                     and before the voices' calls from it, whether or not a voice sounds: state that moves between notes
//                     (a temperature, a display), the same however the host splits its blocks
//   noteOn(float note, float velocity)   each note-on the Engine plays (the player's, or a held key started again on a
//                     new program), before its voice's start(), velocity 0 to 1
//   noteOff(float note)   that note's end, before its voice's stop() where it has one: its note-off, or, the sustain
//                     pedal down, the pedal's going up; All Notes Off; prepare(). Each noteOn gets one noteOff before that
//                     key's next noteOn (a key pressed again while its note is on gets its noteOff first)
// and a param of Shared named as a dial (the main module's parameter, or a circuit's pot or switch) reads that dial:
// reset() sets it to the dial's default before Shared's init (as the instances' are), and the Engine sets it to the
// dial's value at the sample (setSharedDials) before each tick and each note hook, from the first block on: a knob's
// value, never a stream. A param of Shared that no dial is named as keeps its default, with a note. The effect's Shared
// has none of these, its init and end only. They run in the frozen copy too (it looks their shims up), and stop the
// Patch as any audio-thread call does. A program whose Shared ticks is never refined (Compiler.h, "The self-test"): a
// new Patch's Shared starts afresh, so its circuits' self-test answers play from the next RUN.
//
// Mono (an instrument's). A line `#pragma mono` plays the program one voice at a time, and `#pragma mono <dial>` does
// while that dial (a bool, or an int: on when it is not 0) is on, so that the panel switches it; the line is read from
// the files FMinus read, as it read them (a group a conditional skips has none), the first such line alone (another is a
// note, and so is a dial that is not there or is real: the program is then mono always). The Engine plays it (Engine.h,
// "Mono"): the keys held in the order they were pressed, the newest sounding, one voice. Voice may have, optionally:
//   legato(float note, float velocity)   the sounding voice's new note while its key (or the sustain pedal) holds it, in
//                     place of a start and a stop: a key pressed meanwhile, or, its key let go while others are held, the
//                     newest of those at the velocity it was pressed with. Glide is the program's: legato gives the new
//                     note, and process moves to it as it likes. Appended as a nonblocking shim only to a mono program,
//                     and only when declared as here (lang::legatoHook: one declared otherwise is the program's own, with
//                     a note at its place, as is one in a program that is not mono). Without it a new note starts a voice
//                     as a steal does (the voice that sounded gets its stop() and fades out over 2 ms).
// Each start() still gets one stop() before its instance's next start: legato comes between them, never after the stop.
// The effect has no notes: its #pragma mono is a note, and nothing more.
//
// Frozen dials. Once the dials hold still, the plugin compiles the program again with each dial bound as a constant at
// its value (FMinus's Program::Binding::frozen; freeze() below): the optimiser folds what the dials compute, a filter's
// coefficients, a level's expf, a branch on a switch, which an instrument's voices otherwise compute in every call.
// FMinus gives a parameter the same slot in an instance whatever its binding, so the frozen copy runs this Patch's own
// instances: the Engine switches between the two at a block's start (useFrozen) without a seam. The copy compiles in
// FMinus's Math::Fast (LLVM's own sinf, cosf, tanf, expf, tanhf and logf, vectorised where its loops vectorise, a
// constant's folded with this machine's functions): faster than the program's Math::Vector, and the same sound, though
// not the same bits; a result may move in its last bits (a few ulp), and while the copy plays it may depend on where
// the host's blocks end. No fast-math flags: no reassociation, NaN and infinity kept as IEEE has them.
//
// The IR. What FMinus made of a program, as LLVM's textual IR (a .ll file: fminus::Program::Options::keepIr), for the
// editor's IR view: as the code generator wrote it (lowered) and as the JIT made the machine code from it (optimised,
// FMinus's -O2 pipeline). Kept only when asked (compile()'s `keepIr`, freeze()'s `ir`), since printing it costs time and
// the Program holds the text while it lives; ir() and frozenIr() compile a recipe's program again for its text alone
// (no code generated, no instance), with the options compile()'s second pass or freeze() gave it, so the text is the
// one the code that plays came from. The appended calls are in it too (playground_process, ...).
//
// The loop budget (runaway-loop protection). A program that loops for ever holds the thread that calls it: on the audio
// thread, the host's whole session. So every compile that plays (compile()'s second pass, freeze(), ir() and frozenIr())
// has FMinus's loop budget (Program::Options::loopBudget; FMinus's docs/extending.md, recipe 29): the code counts its
// loops' iterations and its recursive calls against a budget the plugin sets before each call, and a call that runs
// past it returns early, with every function of the program it was in. A call within its budget computes what it
// would without it, bit for bit (the checks go in after the optimiser has made every decision). The budget is a count,
// not a clock, set from the call's samples and the rate: kLoopsPerSecond (2^32, about 4.3 billion: about what one
// core runs in a second of loop iterations that take a cycle each, the fewest an iteration takes) for the call's
// samples at the rate, and kBudgetFloor's worth (16 samples) at least, for a call's own setup (start, stop, a
// circuit's set(), a voice's part of a few samples): at 48 kHz 89,478 iterations a sample, 1.43 million for a call of
// 16, 22.9 million for one of 256 and 183 million for one of 2048. So a call stops only after running about as long
// as its samples last, and as many times longer as its loop's iteration takes cycles, which no program that plays in
// real time does; and a call stuck in a loop holds the thread that long: a loop of 50 cycles an iteration about a
// second for a host's block of 1024 at 48 kHz. Only the effect's call grows with the host's block (one a block); the
// synth's calls are its voices' parts, of 16 samples at most. A parallel region's threads count apart (each takes at
// most the budget, FMinus's atomic min), so a call with a region may run its threads' count times as long. init and
// end (each instance's, and Shared's) run off the audio thread with kInitBudget each (2^32: about a second of a
// core's work). dsp.budget measures what the checks cost (README, "A loop that never ends"); the frozen copy keeps
// them.
//
// A call that runs past its budget stops the Patch (stopped(): the call it was). The instances are left as the stopped
// call's optimised code left them, which need be no point of the source (a ring's index past its end), so the Patch
// calls the program no more until reset() makes them as new: every call after a stop does nothing (process leaves the
// buffers as they are, render returns false and writes nothing, start, stop and setCircuits nothing). The Engine fades
// it out (Engine.h, "A program that stops") and the Compiler says why (Compiler.h; stopMessage(): the words, at the
// method's line). An init that runs past it stops the Patch too (the instances after it not initialised, and no end for
// them): compile() then fails with that message, so a program whose init (or Shared's) never ends does not play, as one
// that does not compile does not. An end that runs past it returns early (what it had to free stays allocated), and
// the ends after it are not called. Nor does a stopped Patch's reset() or destructor call any end, each instance's or
// Shared's (a voice may have written Shared): a stopped call may have left the pointers end frees any way (a buffer's
// front and back made one, which end would free twice), so what init allocated stays allocated, a leak where the
// alternative is a crash of the host.
//
// Bounds checks (an index outside its array). An index past an array's end reads or writes whatever lies beside it, in
// the instance or in the host's memory: a write there corrupts the host or crashes it, perhaps much later. So every
// compile that plays as the program is written (compile()'s second pass: RUN's, a refine's, each tool's render; and
// ir(), its text) has FMinus's bounds checks (Program::Options::boundsCheck; FMinus's docs/extending.md, recipe 30):
// every access whose array the compiler sees (a field's, a local's, a constant table's: a[i], m.taps[i], voices[v],
// a + i) is checked against the array's extent, and a call whose check fails returns early, before the access, with
// every function of the program it was in. A call within its arrays computes what it would without them, bit for bit.
// The frozen copy (freeze(), frozenIr()) has none: it is the build that plays once the dials hold still, at full speed,
// and the freezer compiles it anyway, so the two builds take no compile more than one did (dsp.bounds measures what
// the checks cost; README, "An index outside its array"). A pointer the program keeps is not checked, its extent being
// known only as it runs (a heap block from calloc, as delay.fm's line, reverb.fm's and wavetable.fm's table; a host's
// buffer), nor an FFT's buffers against its plan. A failed check stops the Patch as a call past its budget does
// (stopped(): the call it was; bounds(): the check, its file, line, column, array, type, extent and index, copied for
// the Engine to publish), every call after it does nothing until reset(), which empties FMinus's record before any
// init, and stopMessage() words it at the access ("program.fm:14:33: error: process() went outside an array: index
// -188 out of bounds for 'line' of type 'float[512]'"). An init's failed check fails the compile; an end's, the ends.
//
// Samples (dsp/Assets.h: the audio files the user added, the explorer's ASSETS). A line `#pragma sample <field>
// "<file>"` (the quotes optional), read from the files FMinus read as it read them (a skipped group has none), fills
// the field of that name of the main module (in every instance) and of Shared, whichever have it, with the sample of
// that name: a field whose type is a module with `const float* data` and `int frames`, and optionally `int channels`
// and `float rate` (the library's Sample, sample.fm, is one), written after the defaults and before init (reset()): data
// the sound at the rate the Patch plays at (Asset::at: resampled once a rate, off the audio thread), planar, channel c's
// frame i at data[c * frames + i]; frames each channel's, channels 1 or 2, rate the Patch's. The Patch holds the
// sound while it lives (a reset at another rate takes that rate's), so the audio thread only reads it; nothing checks
// the pointer's bounds (a host's buffer: FMinus's checks do not see it), so a program reads within frames. data is
// const alone (FMinus refuses a write through it): the sound is one buffer that every instance, the next compile at
// that rate and the tools' renders share, so a `float* data` makes no sample's field. A file the program's samples
// lack, or a field that is not there or of another type (a `float* data` too), is a note, and the field stays empty
// (frames 0, data null): the program plays, silent where it reads the sample. The recipe keeps the samples (Recipe::
// assets) and what each line read (Recipe::samples: the file and its hash, "" for none), so a refine compiles with the
// same ones, and a panel's edit is one only while the samples it read are the same (Compiler.h).
//
// Threads: compile(), freeze(), ir() and reset() run off the audio thread (or while it is stopped), the calls marked
// noexcept on it. init and end run in flush-to-zero (fsdsp::ScopedFtz), the mode the program is compiled for, on
// whatever thread resets or destroys it.
// The audio thread never destroys a Patch; the Engine hands it back (Engine.h).
